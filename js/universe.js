export const TIER_NAMES = ['звичайне', 'незвичне', 'крайнє', 'легендарне'];
const tiersAt = (qs) => TIER_T.map((T) => pwl(T, qs));
// Значення по один бік за кінцями рівнів e = [центр, межа звичайного, незвичного, крайнього, легендарного]
function tierVal(z, T, e) {
  if (z < T[0]) return e[0] + (e[1] - e[0]) * z / T[0];
  if (z < T[1]) return e[1] + (e[2] - e[1]) * (z - T[0]) / (T[1] - T[0]);
  if (z < T[2]) return e[2] + (e[3] - e[2]) * (z - T[1]) / (T[2] - T[1] || 1);
  return e[3] + (e[4] - e[3]) * (z - T[2]) / (1 - T[2]);
}
const tierOf = (z, T) => z < T[0] ? 0 : z < T[1] ? 1 : z < T[2] ? 2 : 3;
