// Чи левітує порода st за гравітації g (у g) і магнітного поля m (0…1)
export function floats(st, g, m) {
  return st.cond === 0 || (st.cond === 1 && g < st.thr) || (st.cond === 2 && g > st.thr) || (st.cond === 3 && m > st.thr);
}

// Місцева гравітація (аномалії): {k — множник сили, tx, ty — горизонтальна складова (частка g)}. Точна арифметика
// (від неї залежить генерація: левітація каміння в плямі). Поза плямами — {k: 1, tx: 0, ty: 0}
const NO_ANOM = { k: 1, tx: 0, ty: 0 };
export function gravityAt(L, x, y) {
  const A = L.anom;
  if (!A || A.freq < 0.02) return NO_ANOM;
  const a = noise2(L.sAn, x / A.S, y / A.S), thr = 0.62 - 0.32 * A.freq;
  if (a <= thr) return NO_ANOM;
  const s = Math.min(1, (a - thr) / 0.12), b = noise2(L.sAn2, x / (A.S * 2), y / (A.S * 2));
  // зворотна гравітація (легендарний закон, A.rev): у плямах з b < −0,4 біля ґрунту — k₀ (−1…0,1; вище — слабне до 1,
  // worldphys.js gravAt3)
  const rev = !!A.rev && b < -0.4;
  const target = rev ? A.rev.k0 : b > 0 ? 1 + 1.5 * Math.min(1, b * 2.5) : 1 - 0.7 * Math.min(1, -b * 2.5);
  const k = 1 + (target - 1) * s;
  if (!A.tilt) return rev ? { k, tx: 0, ty: 0, rev } : { k, tx: 0, ty: 0 };
  const tx = noise2(L.sAn ^ 0x5151, x / A.S, y / A.S), ty = noise2(L.sAn ^ 0x7373, x / A.S, y / A.S);
  return { k, tx: tx * A.tilt * s * 1.5, ty: ty * A.tilt * s * 1.5, rev };
}

// Рух у всесвіті: на скільки рівнів можна піднятися кроком (up), множник швидкості ходи, як швидко ноги наздоганяють
// нову висоту (легка гравітація — «пливе»), межа швидкості падіння vT (опір повітря: густе й легка гравітація —
// повільне падіння, без повітря — майже без межі), тертя ґрунту (1 — звичайне, менше — ковзко), пружність.
// Зійти пішки можна з будь-якої висоти (шкоди від падіння ще немає)
export function physOf(L, rho = L.air ? L.air.rho : 1.225) {
  const g = L.grav, P = L.phys || { friction: 1, bounce: 0 };
  return {
    up: g < FLOAT_G ? 2 : 1,
    speed: g > 1 ? Math.max(0.55, 1 - 0.18 * (g - 1)) : 1 + 0.1 * (1 - g),
    settle: Math.min(20, Math.max(5, 14 * g)),
    // межа падіння гравця (м/с): вага = опір, m·g = ½·ρ·v²·CdA (m 70 кг, CdA 0,9 м², ρ — густина повітря зі складу й
    // температури, на висоті — з physAt3)
    vT: Math.min(500, Math.sqrt(2 * 70 * 9.81 * g / (Math.max(rho, 1.225e-4) * 0.9))),
    friction: P.friction, bounce: P.bounce,
    g,
  };
}
