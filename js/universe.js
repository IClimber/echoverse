  const wc = 0.3 + U(2, 50), wh = 0.4 + U(3, 25), wd = 0.06 + 0.22 * U(4, 15);
  const contrast = 1.0 + 0.9 * U(5, 35);
  // Клімат: зсуви температури й вологості (−1 холодно/сухо … 1 спекотно/волого)
