// t3 легендарне (відхилення закону z вище порогу — рівень вищий). Класи на глибині 0 далі від старту: 30 % звичайні
// (жодного незвичного), 45 % — 1–3 незвичні закони, 20 % — дивні (багато незвичного, 1–2 крайні), 5 % — дуже дивні
const TIER_T = [[[0, 1], [0.3, 1], [0.75, 0.9], [0.95, 0.75], [1, 0.6]], [[0, 1], [0.75, 1], [0.95, 0.94], [1, 0.85]], [[0, 1], [0.95, 1], [1, 0.985]]];
