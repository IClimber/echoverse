const clamp01 = (v) => v < 0 ? 0 : v > 1 ? 1 : v;
const frac = (v) => v - Math.floor(v);

// HSL → RGB (кусково-лінійно, без тригонометрії)
export function hsl(h, s, l) {
  h = frac(h); s = clamp01(s); l = clamp01(l);
  const q = l < 0.5 ? l * (1 + s) : l + s - l * s, p = 2 * l - q;
  const ch = (t) => {
    t = frac(t);
    const v = t < 1 / 6 ? p + (q - p) * 6 * t : t < 0.5 ? q : t < 2 / 3 ? p + (q - p) * (2 / 3 - t) * 6 : p;
    return Math.round(v * 255);
  };
  return [ch(h + 1 / 3), ch(h), ch(h - 1 / 3)];
}

// Плавний параметр i уздовж номера n з періодом per стрибків: ≈ −0,7…0,7
function lane(ds, i, n, per) {
  const s = ds ^ Math.imul(i + 1, 0x9e3779b9);
  return noise2(s, n / per, i * 7 + 0.5) + 0.25 * noise2(s ^ 0x5bd1e995, n / (per * 0.4), 0.5);   // y — однакова дробова частина: розподіл у всіх законів той самий (qOf)
}

// Розподіл lane (емпірично, 1,28 млн значень, симетричний): |lane| → частка значень нижче. q рівномірне на (0, 1)
const LQ = [[0, 0.5], [0.0935, 0.6], [0.1989, 0.7], [0.3316, 0.8], [0.4111, 0.85], [0.5018, 0.9], [0.5884, 0.94], [0.6752, 0.97], [0.7746, 0.99], [0.8568, 0.997], [0.9219, 0.999], [1.196, 1]];
export function qOf(v) {
  const a = v < 0 ? -v : v;
  let i = 1;
  while (i < LQ.length - 1 && a > LQ[i][0]) i++;
  const [x0, y0] = LQ[i - 1], [x1, y1] = LQ[i], t = a >= x1 ? 1 : (a - x0) / (x1 - x0), q = y0 + (y1 - y0) * t;
  return v < 0 ? 1 - q : q;
}
// Кусково-лінійна функція за вузлами [[x, y], …] (x зростають)
function pwl(T, x) {
  if (x <= T[0][0]) return T[0][1];
  for (let i = 1; i < T.length; i++) if (x <= T[i][0]) { const [x0, y0] = T[i - 1], [x1, y1] = T[i]; return y0 + (y1 - y0) * (x - x0) / (x1 - x0); }
  return T[T.length - 1][1];
}
