// astro.js — фізика планети з законів (п. 4 roadmap, 12.10.2026): зоря → відстань → температура; радіус і густина →
// маса → тяжіння → утримання повітря; обертання → доба, поле; повітря → парниковий ефект. Чисті функції (тести подають
// реальні тіла: Земля, Марс, Місяць, Венера). Точна арифметика (num.js): від цього залежить генерація (тяжіння й
// температура ділянки). Одиниці: радіус і маса — земні, густина — частка земної 5,51 г/см³, g — земне, відстань — а. о.,
// світність — сонячна, температура — K, тиск — атм, час — години.
import { nsqrt, nroot4, pwl, clamp } from './num.js';

// Головна послідовність (Pecaut & Mamajek): температура → [L^¼, R, M]; L — через корінь 4-го степеня (плавно між вузлами)
const MS = [[2400, 0.1316, 0.10, 0.08], [3100, 0.234, 0.20, 0.16], [3600, 0.4325, 0.45, 0.45], [4300, 0.632, 0.70, 0.70], [5000, 0.795, 0.85, 0.85],
  [5772, 1, 1, 1], [6600, 1.316, 1.35, 1.3], [7800, 1.627, 1.6, 1.65], [9800, 2.515, 2.2, 2.4], [20000, 7.4, 5, 7]];
const col = (j) => MS.map((r) => [r[0], r[j]]);
const ML4 = col(1), MR = col(2), MM = col(3);
export const STAR_CLASSES = ['M', 'K', 'G', 'F', 'A', 'B'];
// Зоря з температури T: світність L, радіус R, маса M, клас (індекс STAR_CLASSES), активність act (спалахи, УФ)
export function starOf(T) {
  const l4 = pwl(ML4, T), cls = T < 3900 ? 0 : T < 5300 ? 1 : T < 6000 ? 2 : T < 7500 ? 3 : T < 10000 ? 4 : 5;
  return { T, L: l4 * l4 * l4 * l4, R: pwl(MR, T), M: pwl(MM, T), cls, act: [1, 0.4, 0.3, 0.4, 0.6, 0.6][cls] };
}

// Планета: радіус R, густина без стиснення rho0 → густина (стиснення ×(1 + 0,25R²)), g = ρ·R, маса ρ·R³, швидкість втечі
// (км/с). Земля (1; 0,8) — 1 g; Марс (0,532; 0,68) — 0,38; Місяць (0,273; 0,6) — 0,165; Меркурій (0,383; 0,96) — 0,38
export function planetOf(R, rho0) {
  const rho = rho0 * (1 + 0.25 * R * R), g0 = clamp(rho * R, 0.02, 4);
  return { R, rho0, rho, g0, M: rho * R * R * R, vEsc: 11.19 * R * nsqrt(rho) };
}
// Найкоротший період обертання (розрив), години: 2π·√(R/g) — для Землі 1,406 год
export const pMin = (R, g) => 1.406 * nsqrt(R / g);
// Рівноважна температура (K): інсоляція S (сонячних сталих), альбедо A — Земля (1; 0,3) — 255 K
export const tEq = (S, A) => 278.6 * nroot4(S * (1 - A));

// Повітря: тиск-основа Pb (атм) × утримання (λ — параметр Джинса, Земля ≈ 1: малі й гарячі планети втрачають повітря) ×
// поле B (без поля — вітер зорі здуває; від половини земного — вже тримає); склад — частки O₂, CO₂, SO₂, CH₄ (N₂ — решта). Повертає тиск, склад, молярну
// масу, категорію (gas: 0 придатне, 1 розріджене / мало кисню, 2 задушливе, 3 отруйне, 4 майже немає), парниковий τ
export const GAS_NAMES = ['придатне', 'розріджене', 'задушливе (вуглекислий газ)', 'отруйне (сірчане)', 'майже немає'];
export const VACUUM = 0.002;          // атм: нижче — немає вітру, погоди, хмар, сяйв
export function airOf({ Pb, R, rho, Teq, B, O2, CO2, SO2 = 0, CH4 = 0 }) {
  const lam = 254.6 * R * R * rho / Teq, r = clamp((lam - 0.1) / 0.3, 0, 1);
  const P = Pb * r * r * (0.3 + 0.7 * Math.min(1, 2 * B));
  let o = O2, c = CO2, s = SO2, m = CH4;
  const sum = o + c + s + m;
  if (sum > 1) { o /= sum; c /= sum; s /= sum; m /= sum; }
  const N2 = Math.max(0, 1 - o - c - s - m), mu = 28 * N2 + 32 * o + 44 * c + 64 * s + 16 * m;
  const pO2 = P * o, pCO2 = P * c;
  const gas = P < VACUUM ? 4 : s > 0 ? 3 : pCO2 >= 0.02 ? 2 : P < 0.5 || pO2 < 0.16 ? 1 : 0;
  const gasName = gas === 1 && P >= 0.5 ? 'мало кисню' : GAS_NAMES[gas];
  return { P, lam, keep: r, comp: { N2, O2: o, CO2: c, SO2: s, CH4: m }, mu, gas, gasName, ox: pO2 >= 0.12, tau: 0.84 * P * (1 + 0.76 * c + 3 * m) };
}
// Температура поверхні (K) з парниковим ефектом (сіра атмосфера, Еддінгтон): Земля 288, Венера ~720, Марс ~209
export const tSurf = (Teq, tau) => Teq * nroot4(1 + 0.75 * tau);
// Перенесення тепла повітрям: 1 — земне (різниця екватор — полюс 40 °C), густе — вирівнює, без повітря — 1,4
export const kTr = (P, g) => clamp(1.4 - 0.4 * P / g, 0.1, 1.4);

// Магнітне поле (Земля — 1): рідке залізне ядро (густина без стиснення), розмір, обертання, удача динамо fB
export function fieldOf(rho0, R, Prot, fB) {
  return fB * clamp((rho0 - 0.55) / 0.25, 0, 1.8) * clamp((R - 0.35) / 0.65, 0, 1.6) * clamp(nsqrt(24 / Prot), 0.3, 1.5);
}
// Радіація на поверхні (0…1): активність зорі, захист полем і стовпом повітря (P/g)
export const radOf = (act, B, P, g) => clamp(0.03 + 0.9 * act * clamp(1.1 - B, 0.1, 1.1) / (1 + 4 * P / g), 0, 1);
// Густина повітря біля моря (кг/м³) і висота однорідної атмосфери (м; ×1/8 земної — під наші гори, рішення 12.10.2026)
export const rhoAir = (P, mu, T) => 1.225 * P * (mu / 28.97) * (288.15 / T);
export const scaleH = (T, mu, g) => 1054 * (T / 288) * (28.97 / mu) / g;
