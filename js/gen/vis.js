// Заслони секції для відсікання закритого (js/render/occlusion.js, js/engine/graphics/occluder.js): поверхня «глибокого»
// твердого — блоків, у яких усі 26 сусідів теж тверді. Такий блок цілий усередині плавної поверхні, що малюється:
// вершини Surface Nets (mesh.js) — лише в кубах 2×2×2 центрів блоків, де є не тверде, а грань — між вершинами чотирьох
// кубів навколо ребра «тверде — не тверде»; куби, що заходять у глибокий блок, — з самих його сусідів, усі тверді. Від
// межі глибокого до видимої поверхні — щонайменше пів клітинки. Тож промінь з повітря до будь-якої точки заслону
// раніше перетинає видиму поверхню: заслін не сховає того, що видно.
// Заслони — грані грубих клітинок 2 × 2 × 2 блоки, глибоких цілком (їх утричі-вчетверо менше, ніж граней блоків, а
// запас той самий: груба область — частина глибокої). Сусіда за межею секції вважаємо не глибоким — грань на межі є
// завжди: чи глибока його груба клітинка, рамка в два блоки не скаже, а без грані там, де сусід її не має, в оболонці
// діра (промінь проходить у глибоке без заслону; на тестовому світі — 42 % відсіченого замість 53 %). Зайва грань на
// межі — усередині твердого, не заважає.
// Грані злито жадібно в шарі. Ближче безпечної відстані (js/engine/graphics/occluder.js) клітинка буфера отримує
// глибину за центром — на стиках граней щілин немає, оболонки досить; далі — лише цілком покрита одним заслоном (на
// стиках дрібних граней не закриваємо). Пробували й більші заслони (грань росте в площині поверх глибокого з обох
// боків, усередині твердого): з закритою оболонкою відсікають стільки ж (на 128 клітинках — +1,6 % секцій), а
// перемальовують утричі більше.
// Повертає null (глибокого немає) чи {f, s}: f — Uint8Array по 6 чисел на прямокутник: напрям (0 −x, 1 +x, 2 −y, 3 +y,
// 4 −z, 5 +z — нормаль назовні від глибокого), площина (межа клітинок уздовж осі, 0…16), u0, v0, u1, v1 (клітинки секції,
// кінці не включно; ±x: u — y, v — k; ±y: u — x, v — k; ±z: u — x, v — y); за напрямом, далі за шаром. s — бічні маски,
// Uint8Array(48): для кожної сторони секції (напрям 0…5) 8 байтів — байт v, біт u: груба клітинка біля цієї сторони
// глибока (u, v — у грубих клітинках, осі ті самі). Грань на межі, за якою в сусіда глибоке, закрита його оболонкою —
// js/render/occlusion.js її пропускає. Суцільна секція (порожня з solid) — без масивів: заслін — її межі.
import { bv, solidB } from './chunk.js';

const N = 16, M = N + 4, D = N + 2, G = 2, NG = N / G;   // M — клітинки −2…17 (рамка 2), D — −1…16; G — груба клітинка
const sol = new Uint8Array(M * M * M), e1 = new Uint8Array(M * M * M), e2 = new Uint8Array(M * M * M), deep = new Uint8Array(D * D * D);
const cg = new Uint8Array((NG + 2) ** 3), mask = new Uint8Array(NG * NG), out = [], side = new Uint8Array(48);
const im = (x, y, k) => ((x + 2) * M + y + 2) * M + k + 2;            // x, y, k ∈ −2…17
const id = (x, y, k) => ((x + 1) * D + y + 1) * D + k + 1;            // x, y, k ∈ −1…16
const ig = (x, y, k) => ((x + 1) * (NG + 2) + y + 1) * (NG + 2) + k + 1;   // грубі −1…8

export function secOccluders(b, nk) {
  for (let x = -2; x < N + 2; x++) for (let y = -2; y < N + 2; y++) {
    const o = bv(x, y, 0, nk), i = im(x, y, 0);
    for (let k = -2; k < N + 2; k++) sol[i + k] = solidB(b[o + k]) ? 1 : 0;
  }
  // ерозія кубом 3×3×3 — окремо по осях (мінімум трьох сусідніх)
  for (let x = -1; x <= N; x++) for (let y = -2; y < N + 2; y++) for (let k = -2; k < N + 2; k++)
    e1[im(x, y, k)] = sol[im(x - 1, y, k)] & sol[im(x, y, k)] & sol[im(x + 1, y, k)];
  for (let x = -1; x <= N; x++) for (let y = -1; y <= N; y++) for (let k = -2; k < N + 2; k++)
    e2[im(x, y, k)] = e1[im(x, y - 1, k)] & e1[im(x, y, k)] & e1[im(x, y + 1, k)];
  for (let x = -1; x <= N; x++) for (let y = -1; y <= N; y++) for (let k = -1; k <= N; k++)
    deep[id(x, y, k)] = e2[im(x, y, k - 1)] & e2[im(x, y, k)] & e2[im(x, y, k + 1)];
  // грубі клітинки: глибокі, якщо глибокі всі 8 блоків; за межею секції — не глибокі
  cg.fill(0);
  let any = 0;
  for (let x = 0; x < NG; x++) for (let y = 0; y < NG; y++) for (let k = 0; k < NG; k++) {
    let v = 1;
    for (let q = 0; q < G * G * G && v; q++) v = deep[id(x * G + q % G, y * G + ((q / G) | 0) % G, k * G + ((q / (G * G)) | 0))];
    cg[ig(x, y, k)] = v; any |= v;
  }
  if (!any) return null;
  out.length = 0;
  // грані глибокого в бік не глибокого: шар за шаром, жадібне злиття прямокутників (по v, тоді по u)
  for (let dir = 0; dir < 6; dir++) {
    const ax = dir >> 1, s = dir & 1 ? 1 : -1;
    for (let L = 0; L < NG; L++) {
      let has = 0;
      for (let u = 0; u < NG; u++) for (let v = 0; v < NG; v++) {
        let c, nb;
        if (ax === 0) { c = ig(L, u, v); nb = ig(L + s, u, v); } else if (ax === 1) { c = ig(u, L, v); nb = ig(u, L + s, v); } else { c = ig(u, v, L); nb = ig(u, v, L + s); }
        const f = cg[c] && !cg[nb] ? 1 : 0;
        mask[u * NG + v] = f; has |= f;
      }
      if (!has) continue;
      const plane = (dir & 1 ? L + 1 : L) * G;
      for (let u = 0; u < NG; u++) for (let v = 0; v < NG; v++) {
        if (!mask[u * NG + v]) continue;
        let v1 = v + 1, u1 = u + 1;
        while (v1 < NG && mask[u * NG + v1]) v1++;
        for (; u1 < NG; u1++) { let ok = true; for (let w = v; w < v1; w++) if (!mask[u1 * NG + w]) { ok = false; break; } if (!ok) break; }
        for (let a = u; a < u1; a++) for (let w = v; w < v1; w++) mask[a * NG + w] = 0;
        out.push(dir, plane, u * G, v * G, u1 * G, v1 * G);
      }
    }
  }
  side.fill(0);
  for (let dir = 0; dir < 6; dir++) {
    const ax = dir >> 1, L = dir & 1 ? NG - 1 : 0;
    for (let u = 0; u < NG; u++) for (let v = 0; v < NG; v++) if (cg[ax === 0 ? ig(L, u, v) : ax === 1 ? ig(u, L, v) : ig(u, v, L)]) side[dir * 8 + v] |= 1 << u;
  }
  return { f: Uint8Array.from(out), s: side.slice() };
}
